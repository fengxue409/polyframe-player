//! 出厂解析接口预设库（P10）
//!
//! 与 P8 的采集站预设不同：**解析接口的生存期极短**。2026-10 实测，公开流传的
//! `jx.*` 接口绝大多数已被替换成「江湖路远，后会无期」这类关停公告页，少数被打到
//! Cloudflare。所以这张表的目的不是「保证能用」，而是：
//!  1. 给出一个开箱可见的列表（用户知道这个功能长什么样、怎么加）；
//!  2. 每条都能在界面上「测活」，失效会明确标注，而不是静默报「解析失败」；
//!  3. `direct://` 是零接口直连嗅探，不依赖任何第三方，长期有效。
//!
//! 维护约定：`PRESET_VERSION` 随表变化递增；新增行请先 `?url=<页面>` 手工验证
//! 返回体里确实有 `<video>`/播放器（或直链），并把实测日期写进提交说明。

/// 预设库版本（表内容变化时 +1）
pub const PRESET_VERSION: u32 = 1;

/// 直连嗅探哨兵值：不拼接第三方接口，直接把页面地址交给主进程嗅探
